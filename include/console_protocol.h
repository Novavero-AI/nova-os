/** @name control
    The control channel, from the first process: a CONSOLE_SETUP, its
    kind saying what follows it and what handles it carries. The console
    answers every CONSOLE_SETUP_BACKGROUND, so its end carries
    CHANNEL_RIGHT_WRITE as well as CHANNEL_RIGHT_READ and RIGHT_WAIT.
    A request that fails its check is dropped: the server closes the handles
    it carried and goes on, and answers a request the dispatcher named that
    has a reply with that reply's body alone: the request's transaction, the
    check's status in its status field if it has one, and every other byte
    0.
    A reply or event that fails its check is dropped: the client closes the
    handles it carried and goes on; a call the message answers fails.
    @{ */

/** The display. */
#define CONSOLE_SETUP_DISPLAY 1
/** A session. */
#define CONSOLE_SETUP_SESSION 2
/** The kernel's background, before the display. */
#define CONSOLE_SETUP_BACKGROUND 3
/** The display after a compositor, whose last frame the screen still
    shows (console.md C2). */
#define CONSOLE_SETUP_DISPLAY_AFTER 5
/** The options, once, before the background and the display. */
#define CONSOLE_SETUP_OPTIONS 6
/** A dispatcher's `which` for a message too short to hold the
    selector. */
#define CONSOLE_CONTROL_UNNAMED 0xFFFFFFFF

/** The most bytes a request on the channel holds. */
#define CONSOLE_CONTROL_TO_SERVER_BYTES_MAX 48
/** The most handles a request on the channel carries. */
#define CONSOLE_CONTROL_TO_SERVER_HANDLES_MAX 64
_Static_assert(CONSOLE_CONTROL_TO_SERVER_BYTES_MAX <= CHANNEL_MAX_BYTES, "a message fits a channel");
_Static_assert(CONSOLE_CONTROL_TO_SERVER_HANDLES_MAX <= CHANNEL_MAX_HANDLES, "a message's handles fit a channel");

/** The most bytes a reply or event on the channel holds. */
#define CONSOLE_CONTROL_TO_CLIENT_BYTES_MAX 4
/** The most handles a reply or event on the channel carries. */
#define CONSOLE_CONTROL_TO_CLIENT_HANDLES_MAX 0
_Static_assert(CONSOLE_CONTROL_TO_CLIENT_BYTES_MAX <= CHANNEL_MAX_BYTES, "a message fits a channel");
_Static_assert(CONSOLE_CONTROL_TO_CLIENT_HANDLES_MAX <= CHANNEL_MAX_HANDLES, "a message's handles fit a channel");

