/** A client's end of a session: it writes requests and reads replies,
    and the end may move to the program that is to use it. */
#define CONSOLE_SESSION_RIGHTS (CHANNEL_RIGHT_READ | CHANNEL_RIGHT_WRITE | \
    RIGHT_WAIT | RIGHT_TRANSFER)

/** A request on a session. */
typedef struct {
    UINT32 transaction; /**< echoed in a read's reply (ipc.md I3) */
    UINT32 operation;   /**< CONSOLE_WRITE or CONSOLE_READ */
    UINT32 length;      /**< a write's bytes, or a read's most */
    UINT32 flags;       /**< 0, or CONSOLE_READ_NO_ECHO on a read */
} CONSOLE_REQUEST;

_Static_assert(sizeof(CONSOLE_REQUEST) == 16, "one layout on every target");
_Static_assert(offsetof(CONSOLE_REQUEST, transaction) == 0, "one layout on every target");
_Static_assert(offsetof(CONSOLE_REQUEST, operation) == 4, "one layout on every target");
_Static_assert(offsetof(CONSOLE_REQUEST, length) == 8, "one layout on every target");
_Static_assert(offsetof(CONSOLE_REQUEST, flags) == 12, "one layout on every target");

