    UINT8 *p = (UINT8 *)bytes;
    UINT64 i;

    *byte_count = 0;
    if ((UINT64)handle_count < 1 ||
        (UINT64)handle_count > 1)
        return ERR_INVALID_ARGS;
    for (i = 0; i < 32; i++)
        p[i] = ((const UINT8 *)body)[i];
    out->setup.kind = (UINT32)CONSOLE_SETUP_DISPLAY_AFTER;
