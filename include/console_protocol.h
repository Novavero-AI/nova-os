/** Check a request received on the channel as its description gives:
    writes the selector's value, or the channel's UNNAMED where the
    bytes are too short to hold it, to *which, and returns
    ERR_INVALID_ARGS for a message that breaks its description,
    ERR_NOT_SUPPORTED for a value no request has
    (docs/spec/interface.md P10). */
static inline UINT32 console_control_request_check(const void *bytes,
                                                   UINT32 byte_count,
                                                   const RECEIVED_HANDLE *handles,
                                                   UINT32 handle_count,
                                                   UINT32 *which)
{
    UINT64 selector;
    const UINT8 *p = (const UINT8 *)bytes;

    if ((UINT64)byte_count < 8) {
        *which = CONSOLE_CONTROL_UNNAMED;
        return ERR_INVALID_ARGS;
    }
    selector = ((UINT64)p[4] | (UINT64)p[5] << 8 | (UINT64)p[6] << 16 | (UINT64)p[7] << 24);
    *which = (UINT32)selector;
    if (selector == (UINT64)CONSOLE_SETUP_DISPLAY)
        return console_control_display_check(bytes, byte_count, handles, handle_count);
    if (selector == (UINT64)CONSOLE_SETUP_SESSION)
        return console_control_session_check(bytes, byte_count, handles, handle_count);
    if (selector == (UINT64)CONSOLE_SETUP_BACKGROUND)
        return console_control_background_check(bytes, byte_count, handles, handle_count);
    if (selector == (UINT64)CONSOLE_SETUP_DISPLAY_AFTER)
        return console_control_display_after_check(bytes, byte_count, handles, handle_count);
    if (selector == (UINT64)CONSOLE_SETUP_OPTIONS)
        return console_control_options_check(bytes, byte_count, handles, handle_count);
    return ERR_NOT_SUPPORTED;
}

