/** @name bootstrap
    The channel the platform driver keeps to the input drivers' client
    (input.md K3), as the console takes it: its bootstrap message, then
    one input endpoint a message.
    A reply or event that fails its check ends the client's process.
    @{ */

/** the debug log's resource */
#define CONSOLE_BOOTSTRAP_DEBUG_LOG 0
/** its process, with MAP */
#define CONSOLE_BOOTSTRAP_SELF 1
/** its end of the control channel */
#define CONSOLE_BOOTSTRAP_CONTROL 2
#define CONSOLE_BOOTSTRAP_HANDLES 3 /**< how many handles it carries */

/** The most bytes a reply or event on the channel holds. */
#define CONSOLE_BOOTSTRAP_TO_CLIENT_BYTES_MAX 4
/** The most handles a reply or event on the channel carries. */
#define CONSOLE_BOOTSTRAP_TO_CLIENT_HANDLES_MAX 3
_Static_assert(CONSOLE_BOOTSTRAP_TO_CLIENT_BYTES_MAX <= CHANNEL_MAX_BYTES, "a message fits a channel");
_Static_assert(CONSOLE_BOOTSTRAP_TO_CLIENT_HANDLES_MAX <= CHANNEL_MAX_HANDLES, "a message's handles fit a channel");

/** Check a message received on the channel: returns OK, or
    ERR_INVALID_ARGS at the first rule of its description it breaks
    (docs/spec/interface.md P10).
    The console's bootstrap message: a transaction ID of 0 and these
    handles in this order. */
static inline UINT32 console_bootstrap_start_check(const void *bytes,
                                                   UINT32 byte_count,
                                                   const RECEIVED_HANDLE *handles,
                                                   UINT32 handle_count)
{
    const UINT32 *body = (const UINT32 *)bytes;

    if ((UINT64)byte_count < 4)
        return ERR_INVALID_ARGS;
    if ((UINT64)body[0] != 0)
        return ERR_INVALID_ARGS;
    if ((UINT64)byte_count != 4)
        return ERR_INVALID_ARGS;
    if ((UINT64)handle_count != 3)
        return ERR_INVALID_ARGS;
    if ((UINT64)handles[0].type != (UINT64)TYPE_RESOURCE)
        return ERR_INVALID_ARGS;
    if ((UINT64)handles[1].type != (UINT64)TYPE_PROCESS ||
        ((UINT64)handles[1].rights & (UINT64)(PROCESS_RIGHT_MAP)) != (UINT64)(PROCESS_RIGHT_MAP))
        return ERR_INVALID_ARGS;
    if ((UINT64)handles[2].type != (UINT64)TYPE_CHANNEL ||
        ((UINT64)handles[2].rights & (UINT64)(CHANNEL_RIGHT_READ | CHANNEL_RIGHT_WRITE | RIGHT_WAIT)) != (UINT64)(CHANNEL_RIGHT_READ | CHANNEL_RIGHT_WRITE | RIGHT_WAIT))
        return ERR_INVALID_ARGS;
    return OK;
}

/** Lay the message out in bytes, which is aligned to 8 bytes and
    holds at least the direction's BYTES_MAX: returns OK with the
    message's size in *byte_count, or ERR_INVALID_ARGS with 0 there
    if it breaks the description (docs/spec/interface.md P14).
    The console's bootstrap message: a transaction ID of 0 and these
    handles in this order. */
static inline UINT32 console_bootstrap_start_encode(UINT32 transaction,
                                                    const UINT32 *handles,
                                                    UINT32 handle_count,
                                                    HANDLE_TRANSFER *transfers,
                                                    void *bytes,
                                                    UINT32 *byte_count)
{
    UINT32 *out = (UINT32 *)bytes;

    *byte_count = 0;
    if ((UINT64)handle_count < 3 ||
        (UINT64)handle_count > 3)
        return ERR_INVALID_ARGS;
    out[0] = transaction;
    {
        const UINT64 total = 4;

        if ((UINT64)out[0] != 0)
            return ERR_INVALID_ARGS;
        if (total != 4)
            return ERR_INVALID_ARGS;
    }
    transfers[0].handle = handles[0];
    transfers[0].rights = RESOURCE_RIGHT_USE;
    transfers[1].handle = handles[1];
    transfers[1].rights = PROCESS_RIGHT_MAP;
    transfers[2].handle = handles[2];
    transfers[2].rights = CHANNEL_RIGHT_READ | CHANNEL_RIGHT_WRITE | RIGHT_WAIT;
    *byte_count = (UINT32)4;
    return OK;
}

