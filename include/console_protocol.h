/** @name session
    Sessions (C4). A client writes requests on its end of a session; the
    console answers each read with a CONSOLE_REPLY and the line.
    A request that fails its check ends the connection: the server closes
    the handles it carried and its own end, and answers nothing.
    A reply or event that fails its check is dropped: the client closes the
    handles it carried and goes on; a call the message answers fails.
    @{ */

/** Show the length bytes that follow the request. No reply. */
#define CONSOLE_WRITE 1
/** Read a line of at most length bytes, edited at the console and
    ended by Enter. The reply carries the request's transaction ID, the
    line's length and the line, printable ASCII without its end. A
    session has at most one read waiting. */
#define CONSOLE_READ 2
/** A dispatcher's `which` for a message too short to hold the
    selector. */
#define CONSOLE_SESSION_UNNAMED 0xFFFFFFFF

/** The most bytes a request on the channel holds. */
#define CONSOLE_SESSION_TO_SERVER_BYTES_MAX 4112
/** The most handles a request on the channel carries. */
#define CONSOLE_SESSION_TO_SERVER_HANDLES_MAX 0
_Static_assert(CONSOLE_SESSION_TO_SERVER_BYTES_MAX <= CHANNEL_MAX_BYTES, "a message fits a channel");
_Static_assert(CONSOLE_SESSION_TO_SERVER_HANDLES_MAX <= CHANNEL_MAX_HANDLES, "a message's handles fit a channel");

/** The most bytes a reply or event on the channel holds. */
#define CONSOLE_SESSION_TO_CLIENT_BYTES_MAX 264
/** The most handles a reply or event on the channel carries. */
#define CONSOLE_SESSION_TO_CLIENT_HANDLES_MAX 0
_Static_assert(CONSOLE_SESSION_TO_CLIENT_BYTES_MAX <= CHANNEL_MAX_BYTES, "a message fits a channel");
_Static_assert(CONSOLE_SESSION_TO_CLIENT_HANDLES_MAX <= CHANNEL_MAX_HANDLES, "a message's handles fit a channel");

/** Check a message received on the channel: returns OK, or
    ERR_INVALID_ARGS at the first rule of its description it breaks
    (docs/spec/interface.md P10).
    Show the length bytes that follow the request. No reply. */
static inline UINT32 console_session_write_check(const void *bytes,
                                                 UINT32 byte_count,
                                                 const RECEIVED_HANDLE *handles,
                                                 UINT32 handle_count)
{
    const CONSOLE_REQUEST *body = (const CONSOLE_REQUEST *)bytes;
    UINT64 at, n;

    (void)handles;

    if ((UINT64)byte_count < 16)
        return ERR_INVALID_ARGS;
    if ((UINT64)body->operation != (UINT64)(CONSOLE_WRITE))
        return ERR_INVALID_ARGS;
    if ((UINT64)body->flags != (UINT64)0)
        return ERR_INVALID_ARGS;
    at = 16;
    n = (UINT64)body->length;
    if (n > (UINT64)(CONSOLE_WRITE_MAX))
        return ERR_INVALID_ARGS;
    if (at + n > (UINT64)byte_count)
        return ERR_INVALID_ARGS;
    at += n;
    if (at != (UINT64)byte_count)
        return ERR_INVALID_ARGS;
    if ((UINT64)handle_count != 0)
        return ERR_INVALID_ARGS;
    return OK;
}

/** Lay the message out in bytes, which is aligned to 8 bytes and
    holds at least the direction's BYTES_MAX: returns OK with the
    message's size in *byte_count, or ERR_INVALID_ARGS with 0 there
    if it breaks the description (docs/spec/interface.md P14).
    Show the length bytes that follow the request. No reply. */
static inline UINT32 console_session_write_encode(const CONSOLE_REQUEST *body,
                                                  const UINT8 *text,
                                                  UINT32 text_count,
                                                  void *bytes,
                                                  UINT32 *byte_count)
{
    CONSOLE_REQUEST *out = (CONSOLE_REQUEST *)bytes;
    UINT8 *p = (UINT8 *)bytes;
    UINT64 at, i, n;

    *byte_count = 0;
    if ((UINT64)text_count > (UINT64)(CONSOLE_WRITE_MAX))
        return ERR_INVALID_ARGS;
    for (i = 0; i < 16; i++)
        p[i] = ((const UINT8 *)body)[i];
    out->operation = (UINT32)CONSOLE_WRITE;
    at = 16;
    for (i = 0; i < (UINT64)text_count; i++)
        p[at + i] = text[i];
    at += (UINT64)text_count;
    out->length = (UINT32)text_count;
    {
        const UINT64 total = at;

        if ((UINT64)out->flags != (UINT64)0)
            return ERR_INVALID_ARGS;
        at = 16;
        n = (UINT64)out->length;
        if (n > (UINT64)(CONSOLE_WRITE_MAX))
            return ERR_INVALID_ARGS;
        if (at + n > total)
            return ERR_INVALID_ARGS;
        at += n;
        if (at != total)
            return ERR_INVALID_ARGS;
    }
    *byte_count = (UINT32)at;
    return OK;
}

