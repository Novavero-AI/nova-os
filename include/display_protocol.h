/** Check a message received on the channel: returns OK, or
    ERR_INVALID_ARGS at the first rule of its description it breaks
    (docs/spec/interface.md P10).
    Issue a connection (D5): its record and label, and the compositor's
    end of a channel of CONNECTION_CAPACITY messages the first process
    created, whose other end it gives the connection's holder with
    DISPLAY_CONNECTION_RIGHTS. */
static inline UINT32 display_control_connect_check(const void *bytes,
                                                   UINT32 byte_count,
                                                   const RECEIVED_HANDLE *handles,
                                                   UINT32 handle_count)
{
    const COMPOSITOR_CONNECT_REQUEST *body = (const COMPOSITOR_CONNECT_REQUEST *)bytes;
    const UINT8 *p = (const UINT8 *)bytes;
    UINT64 at, i, j, n;
    UINT32 c, k, lo, hi;

    if ((UINT64)byte_count < 24)
        return ERR_INVALID_ARGS;
    if ((UINT64)body->setup.kind != (UINT64)(COMPOSITOR_CONNECT))
        return ERR_INVALID_ARGS;
    if ((UINT64)body->setup.transaction == 0)
        return ERR_INVALID_ARGS;
    if (!((UINT64)body->mark == (UINT64)0 ||
          (UINT64)body->mark == (UINT64)1))
        return ERR_INVALID_ARGS;
    if (((UINT64)body->layers & ~(UINT64)(DISPLAY_LAYERS)) != 0)
        return ERR_INVALID_ARGS;
    if (((UINT64)body->rights & ~(UINT64)(DISPLAY_RIGHTS)) != 0)
        return ERR_INVALID_ARGS;
    at = 24;
    n = (UINT64)body->label_length;
    if (n > (UINT64)(DISPLAY_LABEL_MAX))
        return ERR_INVALID_ARGS;
    if (at + n > (UINT64)byte_count)
        return ERR_INVALID_ARGS;
    for (i = 0; i < n;) {
        c = p[at + i];
        i++;
        if (c == 0)
            return ERR_INVALID_ARGS;
        if (c < 0x80)
            continue;
        if (c < 0xC2 || c > 0xF4)
            return ERR_INVALID_ARGS;
        k = c < 0xE0 ? 1 : c < 0xF0 ? 2 : 3;
        lo = 0x80;
        hi = 0xBF;
        if (c == 0xE0)
            lo = 0xA0;
        else if (c == 0xED)
            hi = 0x9F;
        else if (c == 0xF0)
            lo = 0x90;
        else if (c == 0xF4)
            hi = 0x8F;
        if (i + k > n || p[at + i] < lo || p[at + i] > hi)
            return ERR_INVALID_ARGS;
        for (j = 1; j < k; j++)
            if ((p[at + i + j] & 0xC0) != 0x80)
                return ERR_INVALID_ARGS;
        i += k;
    }
    at += n;
    if (at != (UINT64)byte_count)
        return ERR_INVALID_ARGS;
    if ((UINT64)handle_count != 1)
        return ERR_INVALID_ARGS;
    if ((UINT64)handles[0].type != (UINT64)TYPE_CHANNEL ||
        ((UINT64)handles[0].rights & (UINT64)(CHANNEL_RIGHT_READ | CHANNEL_RIGHT_WRITE | RIGHT_WAIT)) != (UINT64)(CHANNEL_RIGHT_READ | CHANNEL_RIGHT_WRITE | RIGHT_WAIT))
        return ERR_INVALID_ARGS;
    return OK;
}

