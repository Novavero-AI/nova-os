/** Check a message received on the channel: returns OK, or
    ERR_INVALID_ARGS at the first rule of its description it breaks
    (docs/spec/interface.md P10).
    Make a window: the size wanted, the layer and the surface, and the
    compositor's end of a channel of WINDOW_CAPACITY messages the client
    created, whose other end is the window (D6). */
static inline UINT32 display_connection_window_check(const void *bytes,
                                                     UINT32 byte_count,
                                                     const RECEIVED_HANDLE *handles,
                                                     UINT32 handle_count)
{
    const DISPLAY_WINDOW_REQUEST *body = (const DISPLAY_WINDOW_REQUEST *)bytes;

    if ((UINT64)byte_count < 24)
        return ERR_INVALID_ARGS;
    if ((UINT64)body->header.kind != (UINT64)(DISPLAY_WINDOW))
        return ERR_INVALID_ARGS;
    if ((UINT64)body->header.transaction == 0)
        return ERR_INVALID_ARGS;
    if ((UINT64)body->width < (UINT64)1 ||
        (UINT64)body->width > (UINT64)(WINDOW_WIDTH_MAX))
        return ERR_INVALID_ARGS;
    if ((UINT64)body->height < (UINT64)1 ||
        (UINT64)body->height > (UINT64)(WINDOW_HEIGHT_MAX))
        return ERR_INVALID_ARGS;
    if (!((UINT64)body->layer == (UINT64)(DISPLAY_LAYER_APP) ||
          (UINT64)body->layer == (UINT64)(DISPLAY_LAYER_NOTIFICATION) ||
          (UINT64)body->layer == (UINT64)(DISPLAY_LAYER_OVERLAY) ||
          (UINT64)body->layer == (UINT64)(DISPLAY_LAYER_TRUSTED) ||
          (UINT64)body->layer == (UINT64)(DISPLAY_LAYER_SYSTEM)))
        return ERR_INVALID_ARGS;
    if (!((UINT64)body->surface == (UINT64)(DISPLAY_SURFACE_WINDOW) ||
          (UINT64)body->surface == (UINT64)(DISPLAY_SURFACE_RAISED) ||
          (UINT64)body->surface == (UINT64)(DISPLAY_SURFACE_PANEL)))
        return ERR_INVALID_ARGS;
    if ((UINT64)byte_count != 24)
        return ERR_INVALID_ARGS;
    if ((UINT64)handle_count != 1)
        return ERR_INVALID_ARGS;
    if ((UINT64)handles[0].type != (UINT64)TYPE_CHANNEL ||
        ((UINT64)handles[0].rights & (UINT64)(CHANNEL_RIGHT_READ | CHANNEL_RIGHT_WRITE | RIGHT_WAIT)) != (UINT64)(CHANNEL_RIGHT_READ | CHANNEL_RIGHT_WRITE | RIGHT_WAIT))
        return ERR_INVALID_ARGS;
    return OK;
}

