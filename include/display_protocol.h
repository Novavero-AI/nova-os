/** Check an event received on the channel as its description gives:
    writes the selector's value, or the channel's UNNAMED where the
    bytes are too short to hold it, to *which, and returns
    ERR_INVALID_ARGS for a message that breaks its description,
    ERR_NOT_SUPPORTED for a value no event has
    (docs/spec/interface.md P10). */
static inline UINT32 display_window_event_check(const void *bytes,
                                                UINT32 byte_count,
                                                const RECEIVED_HANDLE *handles,
                                                UINT32 handle_count,
                                                UINT32 *which)
{
    UINT64 selector;
    const UINT8 *p = (const UINT8 *)bytes;

    if ((UINT64)byte_count < 8) {
        *which = DISPLAY_WINDOW_UNNAMED;
        return ERR_INVALID_ARGS;
    }
    selector = ((UINT64)p[4] | (UINT64)p[5] << 8 | (UINT64)p[6] << 16 | (UINT64)p[7] << 24);
    *which = (UINT32)selector;
    if (selector == (UINT64)WINDOW_RELEASED)
        return display_window_released_check(bytes, byte_count, handles, handle_count);
    if (selector == (UINT64)WINDOW_FRAME)
        return display_window_frame_check(bytes, byte_count, handles, handle_count);
    if (selector == (UINT64)WINDOW_CONFIGURE)
        return display_window_configure_check(bytes, byte_count, handles, handle_count);
    if (selector == (UINT64)WINDOW_DROPPED)
        return display_window_dropped_check(bytes, byte_count, handles, handle_count);
    if (selector == (UINT64)WINDOW_KEY)
        return display_window_key_check(bytes, byte_count, handles, handle_count);
    if (selector == (UINT64)WINDOW_POINTER)
        return display_window_pointer_check(bytes, byte_count, handles, handle_count);
    if (selector == (UINT64)WINDOW_ENTER)
        return display_window_enter_check(bytes, byte_count, handles, handle_count);
    if (selector == (UINT64)WINDOW_LEAVE)
        return display_window_leave_check(bytes, byte_count, handles, handle_count);
    return ERR_NOT_SUPPORTED;
}

